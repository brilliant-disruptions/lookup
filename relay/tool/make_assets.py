"""Builds relay/src/assets.ts: the Wallet pass icons (from the app icon)
and the default invite card (night sky, horizon, the firefly, "LookUp").
Run from the repo root: python3 relay/tool/make_assets.py"""
import base64, io, math, random
from PIL import Image, ImageDraw, ImageFilter, ImageFont

icon = Image.open('assets/icon/icon.png').convert('RGBA')

def png(img):
    b = io.BytesIO(); img.save(b, 'PNG', optimize=True); return b.getvalue()

files = {}
for name, size in [('icon.png', 29), ('icon@2x.png', 58), ('icon@3x.png', 87), ('logo.png', 50), ('logo@2x.png', 100)]:
    files[name] = png(icon.resize((size, size), Image.LANCZOS))

# Default card, 1024 x 512 like the app's alert picture.
W, H = 1024, 512
card = Image.new('RGB', (W, H))
d = ImageDraw.Draw(card)
for y in range(H):
    t = y / H
    top, mid, low = (4, 6, 11), (11, 19, 40), (27, 45, 82)
    if t < .7:
        c = tuple(int(top[i] + (mid[i] - top[i]) * t / .7) for i in range(3))
    else:
        c = tuple(int(mid[i] + (low[i] - mid[i]) * (t - .7) / .3) for i in range(3))
    d.line([(0, y), (W, y)], fill=c)
rnd = random.Random(7)
for _ in range(260):
    x, y = rnd.uniform(0, W), rnd.uniform(0, H * .8)
    r = rnd.choice([.6, .8, 1, 1, 1.3, 1.8])
    a = int(rnd.uniform(90, 255) * (1 - y / H * .6))
    d.ellipse([x - r, y - r, x + r, y + r], fill=(a, a, min(255, a + 10)))
# Horizon: rooftops and trees.
ground = (5, 7, 12)
pts = [(0, H)]
for x in range(0, W + 8, 8):
    h = 430 + 10 * math.sin(x / 37) + 8 * abs(math.sin(x / 13)) + (14 if 300 < x < 360 else 0) + (20 if 700 < x < 740 else 0)
    pts.append((x, H - (H - h)))
pts.append((W, H))
d.polygon(pts, fill=ground)
# A pass arc, dashed, and the firefly where it appears.
glow = Image.new('RGBA', (W, H), (0, 0, 0, 0))
g = ImageDraw.Draw(glow)
arc = [(120 + i * 8, 420 - 300 * math.sin(i / 100 * math.pi)) for i in range(101)]
fx, fy = arc[22]
for r, a in [(46, 40), (30, 70), (16, 140)]:
    g.ellipse([fx - r, fy - r, fx + r, fy + r], fill=(196, 245, 94, a))
glow = glow.filter(ImageFilter.GaussianBlur(3))
card.paste(glow, (0, 0), glow)
d = ImageDraw.Draw(card)
for i in range(22, 100, 3):
    d.line([arc[i], arc[i + 1]], fill=(90, 162, 255), width=4)
d.ellipse([fx - 7, fy - 7, fx + 7, fy + 7], fill=(244, 255, 217))
font = ImageFont.truetype('assets/fonts/InterVariable.ttf', 44)
def weight(f, w):
    axes = f.get_variation_axes()
    f.set_variation_by_axes([w if a['name'] in (b'Weight', 'Weight') else min(max(28, a['minimum']), a['maximum']) for a in axes])
weight(font, 700)
d.text((W - 48, 52), 'LookUp', font=font, fill=(244, 246, 250), anchor='ra')
small = ImageFont.truetype('assets/fonts/InterVariable.ttf', 24)
weight(small, 500)
d.text((W - 48, 108), 'Look up with me', font=small, fill=(160, 168, 184), anchor='ra')
files['card.png'] = png(card)
card.save('/tmp/claude-0/default-card.png')

out = ['// Generated by relay/tool/make_assets.py: Wallet pass icons and the default invite card.', '']
out.append('const b64 = (s: string) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));')
out.append('')
out.append('export const passImages: Record<string, Uint8Array> = {')
for n in ['icon.png', 'icon@2x.png', 'icon@3x.png', 'logo.png', 'logo@2x.png']:
    out.append(f"  '{n}': b64('{base64.b64encode(files[n]).decode()}'),")
out.append('};')
out.append('')
out.append(f"export const defaultCard = b64('{base64.b64encode(files['card.png']).decode()}');")
open('relay/src/assets.ts', 'w').write('\n'.join(out) + '\n')
print({k: len(v) for k, v in files.items()})
